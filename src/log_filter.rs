//! Фильтр логирования по умолчанию для рантайма.
//!
//! Вынесен отдельно, потому что используется и основным бинарником (`dagdb`), и
//! нагрузочным инструментом (`loadgen`), который поднимает in-process кластер. У
//! обоих дефолт — `info`: события узлов («нода N получила/переправила/записала
//! транзакцию») полезны для наблюдения за кластером. `RUST_LOG` имеет приоритет.
//!
//! `openraft` при bootstrap пишет диагностические `WARN`/`INFO` о смене
//! membership; чтобы они не засоряли вывод, их шум приглушается явными директивами
//! (можно переопределить через `RUST_LOG`).

/// Возвращает директиву уровня для [`tracing_subscriber::EnvFilter`].
///
/// `verbose` переводит дефолт в `debug`.
pub fn default_filter(verbose: bool) -> String {
    let base = if verbose { "debug" } else { "info" };
    // Приглушаем внутренний шум openraft (bootstrap/membership: `membership_log_id
    // changed: …`), сохраняя события приложения на выбранном уровне. Реальные
    // проблемы протокола видны как `error`.
    format!("{base},openraft=error")
}
